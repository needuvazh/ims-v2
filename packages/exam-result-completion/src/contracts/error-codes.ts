// Error code constants for Exam, Result & Completion Management
export const EXAM_RESULT_COMPLETION_ERROR_CODES = {
  // Exam errors
  EXAM_NOT_FOUND: 'EXAM_NOT_FOUND',
  EXAM_INVALID_STATE: 'EXAM_INVALID_STATE',
  EXAM_MARKS_INVALID: 'EXAM_MARKS_INVALID',
  EXAM_DUPLICATE: 'EXAM_DUPLICATE',
  EXAM_BATCH_NOT_FOUND: 'EXAM_BATCH_NOT_FOUND',

  // Result errors
  RESULT_NOT_FOUND: 'RESULT_NOT_FOUND',
  RESULT_INVALID_STATE: 'RESULT_INVALID_STATE',
  RESULT_MARKS_INVALID: 'RESULT_MARKS_INVALID',
  RESULT_DUPLICATE: 'RESULT_DUPLICATE',
  RESULT_ALREADY_FINALIZED: 'RESULT_ALREADY_FINALIZED',

  // Completion errors
  COMPLETION_NOT_FOUND: 'COMPLETION_NOT_FOUND',
  COMPLETION_INVALID_STATE: 'COMPLETION_INVALID_STATE',
  COMPLETION_DUPLICATE: 'COMPLETION_DUPLICATE',
  COMPLETION_EVIDENCE_STALE: 'COMPLETION_EVIDENCE_STALE',
  COMPLETION_NO_RULE: 'COMPLETION_NO_RULE',

  // Approval errors
  APPROVAL_NOT_FOUND: 'APPROVAL_NOT_FOUND',
  APPROVAL_INVALID_STATE: 'APPROVAL_INVALID_STATE',
  APPROVAL_STAGE_SEQUENCE: 'APPROVAL_STAGE_SEQUENCE',
  APPROVAL_ACTOR_INELIGIBLE: 'APPROVAL_ACTOR_INELIGIBLE',

  // Cross-context errors
  ENROLLMENT_NOT_FOUND: 'ENROLLMENT_NOT_FOUND',
  ENROLLMENT_BATCH_MISMATCH: 'ENROLLMENT_BATCH_MISMATCH',
  TRAINER_NOT_AUTHORIZED: 'TRAINER_NOT_AUTHORIZED',
  BRANCH_MUTATION_FORBIDDEN: 'BRANCH_MUTATION_FORBIDDEN',
} as const;

export type ExamResultCompletionErrorCode =
  (typeof EXAM_RESULT_COMPLETION_ERROR_CODES)[keyof typeof EXAM_RESULT_COMPLETION_ERROR_CODES];

// HTTP status mapping for error codes
export function getHttpStatusCodeForErrorCode(
  errorCode: ExamResultCompletionErrorCode,
): number {
  const notFoundCodes: ExamResultCompletionErrorCode[] = [
    EXAM_RESULT_COMPLETION_ERROR_CODES.EXAM_NOT_FOUND,
    EXAM_RESULT_COMPLETION_ERROR_CODES.RESULT_NOT_FOUND,
    EXAM_RESULT_COMPLETION_ERROR_CODES.COMPLETION_NOT_FOUND,
    EXAM_RESULT_COMPLETION_ERROR_CODES.APPROVAL_NOT_FOUND,
    EXAM_RESULT_COMPLETION_ERROR_CODES.ENROLLMENT_NOT_FOUND,
  ];

  const conflictCodes: ExamResultCompletionErrorCode[] = [
    EXAM_RESULT_COMPLETION_ERROR_CODES.EXAM_DUPLICATE,
    EXAM_RESULT_COMPLETION_ERROR_CODES.RESULT_DUPLICATE,
    EXAM_RESULT_COMPLETION_ERROR_CODES.COMPLETION_DUPLICATE,
    EXAM_RESULT_COMPLETION_ERROR_CODES.RESULT_ALREADY_FINALIZED,
  ];

  const forbiddenCodes: ExamResultCompletionErrorCode[] = [
    EXAM_RESULT_COMPLETION_ERROR_CODES.TRAINER_NOT_AUTHORIZED,
    EXAM_RESULT_COMPLETION_ERROR_CODES.BRANCH_MUTATION_FORBIDDEN,
    EXAM_RESULT_COMPLETION_ERROR_CODES.APPROVAL_ACTOR_INELIGIBLE,
  ];

  if (notFoundCodes.includes(errorCode)) return 404;
  if (conflictCodes.includes(errorCode)) return 409;
  if (forbiddenCodes.includes(errorCode)) return 403;

  // Default to 400 for validation/state errors
  return 400;
}
